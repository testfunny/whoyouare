export function cfTierOf(index: number): CfTier {
  for (const t of CF_TIERS) if (index >= t.min) return t
  return CF_TIERS[CF_TIERS.length - 1]
}

/** 排行：超过 N% 的穿越者 */
export function cfOverPercent(index: number): number {
  return Math.max(3, Math.min(99, Math.round(3 + index * 0.96)))
}

/** 身家倍数：低分亏本，高分起飞 */
export function cfFactor(index: number): number {
  if (index < 20) return 0.3 + (index / 20) * 0.5
  return 0.6 + Math.pow(index / 100, 1.5) * 45
}

export function cfMoney(v: number): string {
  if (v >= 100000000) return `${(v / 100000000).toFixed(1)}亿`
  if (v >= 10000) return `${(v / 10000).toFixed(1)}万`
  return `${Math.round(v)}元`
}

export function cfScore(answers: number[], identity: CfIdentity): {
  index: number
  tier: CfTier
  over: number
  finalMoney: number
  avgMoney: number
  traps: number
  gods: number
  items: { q: CfQ; opt: CfOpt }[]
} {
  const qs = identity.seq.map(id => CF_QS[id]).filter(Boolean)
  const items = answers.map((oi, qi) => ({ q: qs[qi], opt: qs[qi]?.opts[oi] })).filter(x => x.q && x.opt)
  let pts = 0
  let maxPts = 0
  let traps = 0
  let gods = 0
  for (const { q, opt } of items) {
    pts += opt.pts
    if (opt.trap) traps++
    if (opt.god) gods++
    maxPts += Math.max(...q.opts.map(o => o.pts))
  }
  const index = maxPts > 0 ? Math.round((pts / maxPts) * 100) : 0
  const factor = cfFactor(index)
  return {
    index,
    tier: cfTierOf(index),
    over: cfOverPercent(index),
    finalMoney: identity.stash * factor,
    avgMoney: identity.stash * identity.avgFactor,
    traps,
    gods,
    items
  }
}
