/**
 * 兑换码生成器
 *   node scripts/gen-codes.mjs [数量] [系列]
 * 系列：HY（默认，隐藏人格）→ 写入 src/data/codes.gen.ts
 *       CF（穿越暴富）      → 写入 src/data/codes_cf.gen.ts
 * 明文码只打印一次；重新运行同系列会整体替换哈希，旧码全部失效。
 */
import { createHash, randomBytes } from 'node:crypto'
import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ALPHA = 'ABCDEFGHJKMNPQRSTUVWXYZ23456789' // 去掉易混淆的 I L O 0 1
const norm = s => s.toUpperCase().replace(/[^A-Z0-9]/g, '')
const sha256 = s => createHash('sha256').update(s).digest('hex')

function pick(n) {
  const bytes = randomBytes(n)
  let out = ''
  for (let i = 0; i < n; i++) out += ALPHA[bytes[i] % ALPHA.length]
  return out
}

const count = Math.max(1, parseInt(process.argv[2] || '5', 10))
const prefix = (process.argv[3] || 'HY').toUpperCase().replace(/[^A-Z0-9]/g, '') || 'HY'
const genFile = prefix === 'CF' ? 'codes_cf.gen.ts' : 'codes.gen.ts'

const out = []
for (let i = 0; i < count; i++) {
  const code = `${prefix}-${pick(4)}-${pick(4)}`
  out.push({ code, hash: sha256(norm(code)) })
}

const file = resolve(dirname(fileURLToPath(import.meta.url)), '../src/data', genFile)
mkdirSync(dirname(file), { recursive: true })
writeFileSync(
  file,
  `// AUTO-GENERATED by scripts/gen-codes.mjs (series ${prefix}) — do not edit by hand\n` +
  `export const CODE_HASHES: string[] = [\n` +
  out.map(o => `  '${o.hash}',`).join('\n') +
  `\n]\n`,
  'utf8'
)

console.log(`[${prefix}] 已生成 ${count} 个兑换码（明文只显示这一次，请妥善保存）：\n`)
for (const o of out) console.log(`  ${o.code}`)
console.log(`\n哈希已写入: ${file}`)
